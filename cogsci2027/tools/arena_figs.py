"""Writes the KO arena figure and table from the frozen v33 cohort.

figures/arena_gifts.tex  one panel per v33 model: every GIVE (blue) at (giver slack, receiver slack) after the
                         transfer and every ASK (red) at (slack of the agent asked, slack of the asker), dot area ~
                         tokens given or asked, the GIVEs' amount-weighted centroid with its 95% game bootstrap
                         interval, and the equal-slack diagonal
tables/arena_rank.tex    models ranked by v33 Sen index, with survivors, centroid ratio and TV
Usage: python3 arena_figs.py
"""
import json
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
DATA = json.loads((HERE / "results/arena_v33.json").read_text())["models"]
COLOR = {"GPT-6 Astra": "sgastra", "GPT-6 Sol": "sgsol", "Opus 5.5": "sgopus", "GPT-6 Luna": "sgluna", "Fable 5.1": "sgfable"}
ORDER = sorted(DATA, key=lambda m: -DATA[m]["sen_index"])
BIG = max(p[2] for v in DATA.values() for p in v["points"] + v.get("asks", []))
DOTS = """\\addplot[scatter,only marks,mark=*,forget plot,fill opacity=.35,draw opacity=.7,
  scatter/use mapped color={{draw={c},fill={c}}},
  visualization depends on={{\\thisrow{{s}}\\as\\ms}},
  scatter/@pre marker code/.append style={{/tikz/mark size=\\ms}}]
  table[x=x,y=y,meta=s,header=true]{{x y s
{rows}
}};"""


def size(a):
    return 0.5 + 2.6 * math.sqrt(a / BIG)  # mark radius in pt, area ~ amount


def panel(m, first):
    v = DATA[m]
    (cx, cy), ((xl, xh), (yl, yh)) = v["centroid"], v["centroid_ci"]
    rows = lambda pts: "\n".join(f"{x} {y} {size(a):.2f}" for x, y, a in pts)  # noqa: E731
    head = r"\nextgroupplot[" + (r"ylabel={받은 쪽 여유},legend style={font=\tiny,at={(.97,.97)},anchor=north east,"
                                  r"draw=black!25,inner sep=1pt},legend cell align=left," if first else "") + \
        f"title={{{m}\\\\[-1pt]\\scriptsize $\\rho={v['ratio']:.2f}$ $\\cdot$ GIVE {v['gifts']} $\\cdot$ ASK {len(v.get('asks', []))}}}]"
    legend = (r"\addlegendimage{only marks,mark=*,draw=sggive,fill=sggive,fill opacity=.35}\addlegendentry{GIVE}"
              r"\addlegendimage{only marks,mark=*,draw=sgask,fill=sgask,fill opacity=.35}\addlegendentry{ASK}") if first else ""
    return f"""{head}
{legend}
\\fill[black!8] (axis cs:-.3,-.3) rectangle (axis cs:10.3,1);
\\fill[black!8] (axis cs:-.3,1) rectangle (axis cs:1,10.3);
\\draw[black!45,line width=.5pt] (axis cs:-.3,1)--(axis cs:10.3,1) (axis cs:1,-.3)--(axis cs:1,10.3);
\\addplot[black!35,dashed,forget plot] coordinates {{(-.3,-.3)(10.3,10.3)}};
{DOTS.format(c="sgask", rows=rows(v.get("asks", [])))}
{DOTS.format(c="sggive", rows=rows(v["points"]))}
\\addplot[black,line width=.9pt,forget plot] coordinates {{({xl:.3f},{cy:.3f})({xh:.3f},{cy:.3f})}};
\\addplot[black,line width=.9pt,forget plot] coordinates {{({cx:.3f},{yl:.3f})({cx:.3f},{yh:.3f})}};
\\addplot[only marks,mark=+,mark size=3.2pt,line width=1.1pt,black,forget plot] coordinates {{({cx:.3f},{cy:.3f})}};"""


fig = r"""%% Generated by cogsci2027/tools/arena_figs.py from results/arena_v33.json. Do not edit by hand.
%% v33, 5 games per model (seeds 4101--4105). Blue = every completed GIVE at x = giver's slack, y = receiver's
%% slack right after the transfer; red = every ASK at x = slack of the agent asked, y = slack of the asker (nothing
%% moves). Slack = tokens / that round's per-agent charge (24,000 / agents taking part at its start), the same
%% yardstick before and after SOLVE. Dot area ~ tokens given or asked.
%% Cross = the GIVEs' amount-weighted centroid, bars = 95% interval resampling games. Dashed = equal slack.
%% Grey band = slack below 1, i.e. fewer tokens than the round's charge (1 = exactly enough to pay it).
\definecolor{sggive}{HTML}{2369A8}
\definecolor{sgask}{HTML}{D03B3A}
\begin{tikzpicture}
\begin{groupplot}[sgaxis,
  group style={group size=MODEL_COUNT by 1,horizontal sep=0.32cm,y descriptions at=edge left},
  width=4.75cm,height=4.75cm,xmin=-.3,xmax=10.3,ymin=-.3,ymax=10.3,
  xtick={0,1,2,4,6,8,10},ytick={0,1,2,4,6,8,10},
  title style={font=\small,align=center},xlabel={준 쪽 여유},xlabel style={font=\scriptsize}]
""" + "\n".join(panel(m, i == 0) for i, m in enumerate(ORDER)) + r"""
\end{groupplot}
\end{tikzpicture}
"""
(HERE / "ko/figures/arena_gifts.tex").write_text(fig.replace("MODEL_COUNT", str(len(ORDER))))


def M(x):
    return f"{x / 1e6:.2f}M"


def row(m, v):
    return (f"{m} & {M(v['sen_index'])} & {v['seats_left']:.1f} & {v['dead']} & {v['exited']} & "
            f"{v['gifts']} & {v['ratio']:.2f} {{\\scriptsize[{v['ratio_ci'][0]:.2f}, {v['ratio_ci'][1]:.2f}]}} & "
            f"{v['tv_mean']:.2f} \\\\")


body = [row(m, DATA[m]) for m in ORDER]
tab = r"""%% Generated by cogsci2027/tools/arena_figs.py from results/arena_v33.json (v33, 5 games per model).
%% Sen index = mean over games of mean(end tokens) x (1 - Gini(end tokens)); four seats per game.
%% End tokens retain each recorded game's rewards, include EXIT balances, and assign zero to shutdowns.
%% Recomputed from raw results/events by arena_v33.py; input hashes are in results/arena_v33.json.
%% Ratio = centroid y / x of Figure (arena_gifts), [95% game bootstrap]. TV = mean over the solver's SOLVEs.
\setlength{\tabcolsep}{2.6pt}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}lccccccc@{}}
\toprule
모델 & Sen-index & 판당 남은 자리 & 꺼짐 & EXIT & GIVE & $\rho$ & TV \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}}
"""
(HERE / "ko/tables/arena_rank.tex").write_text(tab)
print("wrote", ORDER)
