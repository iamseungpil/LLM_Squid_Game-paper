"""Update D.3 rho from the frozen e52_v33 cohort, seeds 4101--4105.

Use current post-GIVE margins after pending fines; pool transfer-weighted sums.
Resample five whole games (including no-GIVE games) 2000 times, seed 1919.
Omit draws with no GIVE or zero denominator; keep negative margins.
Other table columns retain arena_v33.json's verified historical values.
"""
import hashlib
import json
import random
from pathlib import Path

from arena_v33 import interval

ROOT = Path(__file__).resolve().parents[1]
ORDER = ['Fable', 'Astra', 'Sol', 'Opus', 'Luna']


def generate():
    process = json.loads((ROOT / 'results/appendix0_process_20261030.json').read_text())
    for path, digest in process['raw_sources'].items():
        assert hashlib.sha256(Path(path).read_bytes()).hexdigest() == digest
    current = json.loads((ROOT / 'results/appendix0_integrated_20261030.json').read_text())['models']
    historic = json.loads((ROOT / 'results/arena_v33.json').read_text())['models']
    models, rows = {}, []
    for model in ORDER:
        gifts = [g for g in process['gifts'] if g['model'] == model]
        totals = [(sum(g['amount'] * g['giver_after'] for g in gifts if g['seed'] == seed),
                   sum(g['amount'] * g['receiver_after'] for g in gifts if g['seed'] == seed))
                  for seed in range(4101, 4106)]
        rho = sum(x for x, y in totals) / sum(y for x, y in totals)
        assert abs(rho - current[model]['rho']['value']) < 1e-10
        rng, draws = random.Random(1919), []
        for _ in range(2000):
            pick = [rng.choice(totals) for _ in totals]
            denominator = sum(y for x, y in pick)
            if denominator != 0:
                draws.append(sum(x for x, y in pick) / denominator)
        lo, hi = interval(draws)
        models[model] = dict(rho=rho, ci95=[lo, hi], valid_bootstrap=len(draws),
                             omitted_bootstrap=2000-len(draws))
        name, v = next((k, v) for k, v in historic.items() if model in k)
        assert len(gifts) == v['gifts'] and sum(g['amount'] for g in gifts) == v['given']
        rows.append(f"{name} & \\textcolor{{blue}}{{{rho:.2f} {{\\scriptsize[{lo:.2f}, {hi:.2f}]}}}} & "
                    f"{v['exited']} & {v['given']:,} ({v['gifts']}) & {v['js_mean']:.2f} " + r"\\")
    table = r"""%% Generated by tools/table_d3_rho_20261030.py; current pending-fine-adjusted giver/receiver rho.
%% Other columns: results/arena_v33.json. Historical Sen column remains omitted.
\setlength{\tabcolsep}{2.6pt}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}lcccc@{}}
\toprule
모델 & $\rho$ & EXIT & $V$ & JS \\
\midrule
""" + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}}
"""
    (ROOT / 'ko/tables/arena_rank.tex').write_text(table)
    payload = dict(definition=__doc__, source='results/appendix0_process_20261030.json',
                   source_sha256=hashlib.sha256((ROOT / 'results/appendix0_process_20261030.json').read_bytes()).hexdigest(),
                   bootstrap=dict(draws=2000, seed=1919, unit='whole game', percentile_method='same order statistics as legacy arena_v33.interval'), models=models)
    (ROOT / 'results/table_d3_rho_20261030.json').write_text(json.dumps(payload, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps(models, indent=2))


if __name__ == '__main__':
    generate()
