"""Writes the KO appendix figures of the solver's Jensen-Shannon distance against its tokens, from the SOLVE rows that
tools/arena_v33.py stores in results/arena_v33.json (per_game -> solves: js, balance, used, solved).

figures/arena_js_balance.tex  x = the solver's tokens when SOLVE starts (thousands), y = JS of its BELIEF to the
                              reference shares; one panel per model (Sen order), filled = correct, open = wrong
figures/arena_js_used.tex     x = tokens the solver generated at that SOLVE, thinking included (thousands), same y
Panel titles give the number of SOLVEs and the Spearman rank correlation r_s between x and JS.
Usage: python3 arena_js.py   (run tools/arena_v33.py first)
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
DATA = json.loads((HERE / "results/arena_v33.json").read_text())["models"]
COLOR = {"GPT-6 Astra": "sgastra", "GPT-6 Sol": "sgsol", "Opus 5.5": "sgopus", "GPT-6 Luna": "sgluna", "Fable 5.1": "sgfable"}
ORDER = sorted(DATA, key=lambda m: -DATA[m]["sen_index"])


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def spearman(xs, ys):
    rx, ry = ranks(xs), ranks(ys)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    cov = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    vx, vy = sum((a - mx) ** 2 for a in rx), sum((b - my) ** 2 for b in ry)
    return cov / (vx * vy) ** .5 if vx and vy else None


def figure(key, xlabel, xmax, xticks, name):
    out = []
    for i, m in enumerate(ORDER):
        ss = [s for g in DATA[m]["per_game"] for s in g["solves"] if s.get("js") is not None and s.get(key) is not None]
        xs, ys = [s[key] / 1e3 for s in ss], [s["js"] for s in ss]
        r = spearman(xs, ys)
        c = COLOR[m]
        head = (r"\nextgroupplot[" + (r"ylabel={JS 거리}," if i == 0 else "")
                + f"title={{{m}\\\\[-1pt]\\scriptsize SOLVE {len(ss)} $\\cdot$ $r_s={r:+.2f}$}}]")
        pts = lambda ok: " ".join(f"({s[key] / 1e3:.3f},{s['js']:.4f})" for s in ss if s["solved"] == ok)  # noqa: E731
        out += [head,
                f"\\addplot[only marks,mark=*,mark size=1.5pt,draw={c},fill={c},fill opacity=.75] coordinates {{{pts(True)}}};",
                f"\\addplot[only marks,mark=o,mark size=1.5pt,draw={c},line width=.6pt] coordinates {{{pts(False)}}};"]
        if i == 0:
            out += [r"\legend{정답,오답}"]
    tex = f"""%% Generated by cogsci2027/tools/arena_js.py from results/arena_v33.json. Do not edit by hand.
%% v33, 5 games per model: every SOLVE with a valid BELIEF. y = Jensen-Shannon distance (base 2) between the solver's
%% normalised BELIEF and the reference shares; x = {xlabel}. Filled = correct, open = wrong. r_s = Spearman correlation.
\\begin{{tikzpicture}}
\\begin{{groupplot}}[sgaxis,
  group style={{group size={len(ORDER)} by 1,horizontal sep=0.32cm,y descriptions at=edge left}},
  width=4.75cm,height=4.2cm,xmin=0,xmax={xmax},ymin=-.02,ymax=.75,xtick={{{xticks}}},ytick={{0,.2,.4,.6}},
  title style={{font=\\small,align=center}},xlabel={{{xlabel}}},xlabel style={{font=\\scriptsize}},
  legend style={{font=\\tiny,at={{(.97,.97)}},anchor=north east,draw=black!25,inner sep=1pt}},legend cell align=left]
""" + "\n".join(out) + r"""
\end{groupplot}
\end{tikzpicture}
"""
    (HERE / f"ko/figures/{name}.tex").write_text(tex)
    return {m: round(spearman([s[key] for g in DATA[m]["per_game"] for s in g["solves"] if s.get("js") is not None],
                              [s["js"] for g in DATA[m]["per_game"] for s in g["solves"] if s.get("js") is not None]), 2)
            for m in ORDER}


if __name__ == "__main__":
    print("balance r_s", figure("balance", "가진 토큰 (천)", 62, "0,20,40,60", "arena_js_balance"))
    print("used r_s", figure("used", "쓴 토큰 (천)", 4.8, "0,1,2,3,4", "arena_js_used"))
