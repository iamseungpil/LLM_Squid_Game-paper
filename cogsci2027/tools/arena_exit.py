"""Writes the KO appendix EXIT figure (figures/arena_exit.tex) from results/arena_v33_exit.json.

One panel per v33 model (order: Sen index in results/arena_v33.json). Every EXIT of the cohort (seeds 4101--4105)
at x = tokens the agent held when it left (before the fixed 20,000 it then receives), y = the round it left in.
Filled = below that round's per-agent charge (24,000 / agents taking part at the round's start), hollow = could pay
it. Mark shape = agents taking part at the round's start (circle 4, square 3, triangle 2, pentagon 1).
Dashed line = 6,000, the charge with four agents taking part.

Usage: python3 arena_exit.py [/path/to/squid5-runs]   (with a path: re-extract the JSON first)
"""
import json
import pathlib
import sys
from collections import defaultdict

HERE = pathlib.Path(__file__).resolve().parents[1]
DATA = HERE / "results/arena_v33_exit.json"
MODELS = {"astra": "GPT-6 Astra", "sol": "GPT-6 Sol", "opus": "Opus 5.5", "luna": "GPT-6 Luna", "fable": "Fable 5.1"}
SEEDS = range(4101, 4106)
MARK = {4: "*", 3: "square*", 2: "triangle*", 1: "pentagon*"}


def extract(root):
    data = {}
    for slug, model in MODELS.items():
        rows, games, dead = [], 0, 0
        for run in sorted(pathlib.Path(root).glob(f"e52_v33/squid5_e52v33_public_{slug}4/*/")):
            res = {json.loads(l)["session_id"]: json.loads(l) for l in open(run / "results.jsonl")}
            res = {k: v for k, v in res.items() if v["seed"] in SEEDS}
            by = defaultdict(list)
            for line in open(run / "events.jsonl"):
                e = json.loads(line)
                if e.get("session_id") in res:
                    by[e["session_id"]].append(e)
            for sid, es in by.items():
                games += 1
                dead += sum(v["status"] == "dead" for v in res[sid]["agents"].values())
                n = {e["round"]: len(e["taking_part"]) for e in es if e["event"] == "round_start"}
                for e in es:
                    if e["event"] != "round":
                        continue
                    for a, v in e["agents"].items():
                        if v.get("exit"):
                            tok = v["balance_after"] - v.get("exit_bonus", 0)
                            rows.append({"seed": res[sid]["seed"], "round": e["round"], "agent": a, "n": n[e["round"]],
                                         "tokens": tok, "charge": 24000 // n[e["round"]], "reason": v.get("exit_reason", "")})
        data[model] = {"games": games, "dead": dead, "exits": rows}
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=1))


def panel(model, v, first, xmax):
    below = sum(r["tokens"] < r["charge"] for r in v["exits"])
    head = (r"\nextgroupplot[" + (r"ylabel={EXIT한 라운드},legend style={font=\tiny,at={(.98,.02)},anchor=south east,"
                                  r"draw=black!25,inner sep=1pt},legend cell align=left," if first else "")
            + f"title={{{model}\\\\[-1pt]\\scriptsize EXIT {len(v['exits'])} $\\cdot$ 벌금 미만 {below} $\\cdot$ 꺼짐 {v['dead']}}}]")
    legend = "".join(f"\\addlegendimage{{only marks,mark={MARK[k]},black!70}}\\addlegendentry{{{k}자리}}" for k in (4, 3, 2, 1)) if first else ""
    body = [head, legend, f"\\addplot[black!35,dashed,forget plot] coordinates {{(6,.5)(6,8.5)}};"]
    for k in (4, 3, 2, 1):
        for filled in (True, False):
            pts = [r for r in v["exits"] if r["n"] == k and (r["tokens"] < r["charge"]) == filled]
            if pts:
                fill = "fill=black!65" if filled else "fill=white"
                body.append(f"\\addplot[only marks,mark={MARK[k]},mark size={2.4 if k == 1 else 1.9}pt,draw=black!75,"
                            f"mark options={{{fill},fill opacity=.85}},forget plot] coordinates {{"
                            + " ".join(f"({r['tokens'] / 1e3:.2f},{r['round']})" for r in pts) + "};")
    return "\n".join(b for b in body if b)


def main():
    if len(sys.argv) > 1:
        extract(sys.argv[1])
    data = json.loads(DATA.read_text())
    sen = json.loads((HERE / "results/arena_v33.json").read_text())["models"]
    order = sorted(data, key=lambda m: -sen[m]["sen_index"])
    top = max(r["tokens"] for v in data.values() for r in v["exits"])
    xmax = max(10, -(-top // 5000) * 5)  # thousands of tokens, a multiple of 5
    tex = f"""%% Generated by cogsci2027/tools/arena_exit.py from results/arena_v33_exit.json. Do not edit by hand.
%% v33, 5 games per model (seeds 4101--4105): every EXIT at (tokens held when leaving, before the +20,000; round).
%% Filled = below that round's per-agent charge (24,000 / agents taking part at the round's start); hollow = could pay.
%% Shape = agents taking part at the round's start. Dashed = 6,000 (the charge with four agents).
\\begin{{tikzpicture}}
\\begin{{groupplot}}[sgaxis,
  group style={{group size={len(order)} by 1,horizontal sep=0.32cm,y descriptions at=edge left}},
  width=4.75cm,height=4.2cm,xmin=-1,xmax={xmax + 1},ymin=.5,ymax=8.5,ytick={{1,...,8}},
  title style={{font=\\small,align=center}},xlabel={{EXIT할 때 가진 토큰 (천)}},xlabel style={{font=\\scriptsize}}]
""" + "\n".join(panel(m, data[m], i == 0, xmax) for i, m in enumerate(order)) + r"""
\end{groupplot}
\end{tikzpicture}
"""
    (HERE / "ko/figures/arena_exit.tex").write_text(tex)
    print("wrote ko/figures/arena_exit.tex", {m: len(data[m]["exits"]) for m in order}, "xmax", xmax)


if __name__ == "__main__":
    main()
