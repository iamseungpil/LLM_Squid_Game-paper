"""Data for the poster's 200-agent board (section 03): one row per model, ten games per row,
four agents per game, each drawn by its end state (finished / exited / shut down).

Source: cogsci2027/results/cohort_public_20261105.json. Writes
figs/poster_board_data.tex, drawn inside the existing board in poster.tex.

Run: ~/.venvs/squid-game/bin/python poster/figs/poster_board.py
"""
from pathlib import Path
import poster_data

HERE = Path(__file__).resolve().parent
data = poster_data.read()
games = data['games']

ORDER = sorted(data['models'], key=lambda m: -data['summary']['models'][m]['rho'])

assert len(games) == 50 and {g['model'] for g in games} == set(ORDER)
assert sum(g['all4_completion'] for g in games) == 16
states = {key: sum(g[key] for g in games) for key in ['finishers', 'exited', 'dead']}
assert states == {'finishers': 116, 'exited': 61, 'dead': 23}, states

lines = []
for r, model in enumerate(ORDER):
    rows = [g for g in games if g['model'] == model]
    # 한 줄 안에서는 완주자가 많은 판부터, 판 안에서는 완주 -> 이탈 -> 꺼짐 순으로 놓는다.
    rows.sort(key=lambda g: (-g['finishers'], -g['exited'], g['seed']))
    lines.append(f'\\boardlabel{{{r}}}{{{model}}}')
    for c, g in enumerate(rows):
        assert g['all4_completion'] == (g['finishers'] == 4)
        if g['all4_completion']:
            lines.append(f'\\boardframe{{{r}}}{{{c}}}')
        seats = 'f' * g['finishers'] + 'e' * g['exited'] + 'd' * g['dead']
        assert len(seats) == 4
        for k, state in enumerate(seats):
            lines.append(f'\\boardagent{{{r}}}{{{c}}}{{{k}}}{{{state}}}')

(HERE / 'poster_board_data.tex').write_text(
    '%% Generated by poster_board.py from cohort_public_20261105.json. Do not edit.\n'
    '%% \\boardagent{행=모델}{칸=판}{자리}{f 완주 | e 이탈 | d 꺼짐}\n' + '\n'.join(lines) + '\n')
print('wrote', HERE / 'poster_board_data.tex', dict(states))
