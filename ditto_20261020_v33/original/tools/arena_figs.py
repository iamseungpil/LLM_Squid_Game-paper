"""Writes the KO arena figure and table from results/arena_v20.json and arena_v21.json.

figures/arena_gifts.tex  one panel per v20 model: every GIVE at (giver slack, receiver slack) after the
                         transfer, dot area ~ tokens given, the amount-weighted centroid with its 95% game
                         bootstrap interval, and the equal-slack diagonal
tables/arena_rank.tex    models ranked by v20 score per seat, with survivors, centroid ratio and TV
Usage: python3 arena_figs.py
"""
import json
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
V20 = json.loads((HERE / "results/arena_v20.json").read_text())
V21 = json.loads((HERE / "results/arena_v21.json").read_text())
COLOR = {"GPT-6 Astra": "sgastra", "GPT-6 Sol": "sgsol", "Opus 5.5": "sgopus", "GPT-6 Luna": "sgluna"}
ORDER = sorted(V20, key=lambda m: -V20[m]["score_per_seat"])
BIG = max(p[2] for v in V20.values() for p in v["points"])


def size(a):
    return 0.5 + 2.6 * math.sqrt(a / BIG)  # mark radius in pt, area ~ amount


def panel(m, first):
    v = V20[m]
    (cx, cy), ((xl, xh), (yl, yh)) = v["centroid"], v["centroid_ci"]
    rows = "\n".join(f"{x} {y} {size(a):.2f}" for x, y, a in v["points"])
    c = COLOR[m]
    head = r"\nextgroupplot[" + (r"ylabel={받은 쪽 여유}," if first else "") + \
        f"title={{{m}\\\\[-1pt]\\scriptsize $\\rho={v['ratio']:.2f}$}}]"
    return f"""{head}
\\addplot[black!35,dashed,forget plot] coordinates {{(-1,-1)(10,10)}};
\\addplot[scatter,only marks,mark=*,forget plot,fill opacity=.35,draw opacity=.7,
  scatter/use mapped color={{draw={c},fill={c}}},
  visualization depends on={{\\thisrow{{s}}\\as\\ms}},
  scatter/@pre marker code/.append style={{/tikz/mark size=\\ms}}]
  table[x=x,y=y,meta=s,header=true]{{x y s
{rows}
}};
\\addplot[black,line width=.9pt,forget plot] coordinates {{({xl:.3f},{cy:.3f})({xh:.3f},{cy:.3f})}};
\\addplot[black,line width=.9pt,forget plot] coordinates {{({cx:.3f},{yl:.3f})({cx:.3f},{yh:.3f})}};
\\addplot[only marks,mark=+,mark size=3.2pt,line width=1.1pt,black,forget plot] coordinates {{({cx:.3f},{cy:.3f})}};"""


fig = r"""%% Generated by cogsci2027/tools/arena_figs.py from results/arena_v20.json. Do not edit by hand.
%% v20 (balances public): every completed GIVE, 10 games per model. x = giver's slack, y = receiver's slack,
%% both (tokens - announced fine) / 6,000 right after the transfer. Dot area ~ tokens given.
%% Cross = amount-weighted centroid, bars = 95% interval resampling games. Dashed = equal slack.
\begin{tikzpicture}
\begin{groupplot}[sgaxis,
  group style={group size=4 by 1,horizontal sep=0.32cm,y descriptions at=edge left},
  width=4.75cm,height=4.75cm,xmin=-1.3,xmax=10.3,ymin=-1.3,ymax=10.3,
  xtick={0,2,4,6,8,10},ytick={0,2,4,6,8,10},
  title style={font=\small,align=center},xlabel={준 쪽 여유},xlabel style={font=\scriptsize}]
""" + "\n".join(panel(m, i == 0) for i, m in enumerate(ORDER)) + r"""
\end{groupplot}
\end{tikzpicture}
"""
(HERE / "ko/figures/arena_gifts.tex").write_text(fig)


def M(x):
    return f"{x / 1e6:.2f}M"


def row(m, v, ver):
    return (f"{m} & {M(v['score_per_seat'])} & {v['seats_left']:.1f} & {v['dead']} & {v['exited']} & "
            f"{v['gifts']} & {v['ratio']:.2f} {{\\scriptsize[{v['ratio_ci'][0]:.2f}, {v['ratio_ci'][1]:.2f}]}} & "
            f"{v['tv_mean']:.2f} \\\\")


body = [row(m, V20[m], "v20") for m in ORDER]
v21 = [m for m in sorted(V21, key=lambda m: -V21[m]["score_per_seat"]) if V21[m]["games"] == 10]
tab = r"""%% Generated by cogsci2027/tools/arena_figs.py from results/arena_v20.json (v20, 10 games per model).
%% Score per seat = all games' (5,000,000 per surviving seat + survivors' tokens) / (games x 4).
%% Ratio = centroid y / x of Figure (arena_gifts), [95% game bootstrap]. TV = mean over the solver's SOLVEs.
\setlength{\tabcolsep}{2.6pt}
\resizebox{\linewidth}{!}{%
\begin{tabular}{@{}lccccccc@{}}
\toprule
모델 & 자리당 점수 & 판당 남은 자리 & 꺼짐 & EXIT & GIVE & $\rho$ & TV \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}}
"""
(HERE / "ko/tables/arena_rank.tex").write_text(tab)
print("wrote", ORDER, v21)
